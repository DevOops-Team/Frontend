import { describe, expect, it } from 'vitest';
import { render, screen } from '@testing-library/react';
import userEvent from '@testing-library/user-event';
import { App } from './App';

describe('guided distributed mock', () => {
  it('explains the two supported choices and preserves FSDP in the submitted run', async () => {
    const user = userEvent.setup();
    render(<App />);
    await user.click(screen.getByRole('button', { name: '새 학습 만들기' }));
    await user.click(screen.getByRole('button', { name: '다음: 데이터 입력' }));
    expect(screen.getByRole('alert')).toHaveTextContent('학습 모델');
    await user.type(screen.getByLabelText('학습 이름'), 'my-fsdp');
    await user.type(screen.getByLabelText('학습 모델'), '내 모델 / custom-v99');
    await user.click(screen.getByRole('button', { name: '다음: 데이터 입력' }));
    await user.click(screen.getByRole('button', { name: '다음: 학습 방식' }));
    expect(screen.getByRole('alert')).toHaveTextContent('학습 데이터');
    await user.type(screen.getByLabelText('학습 데이터'), 'anything://내 데이터/mixed.bin');
    await user.click(screen.getByRole('button', { name: '다음: 학습 방식' }));
    expect(screen.getByRole('radio', { name: /DDP/ })).toBeChecked();
    await user.click(screen.getByRole('radio', { name: /FSDP/ }));
    await user.click(screen.getByRole('button', { name: 'GPU 설정' }));
    expect(screen.getByRole('dialog', { name: '학습에 사용할 GPU' })).toBeInTheDocument();
    await user.selectOptions(screen.getByLabelText('총 GPU 개수'), '4');
    await user.keyboard('{Escape}');
    expect(screen.queryByRole('dialog')).not.toBeInTheDocument();
    await user.click(screen.getByRole('button', { name: 'GPU 설정' }));
    expect(screen.getByLabelText('총 GPU 개수')).toHaveValue('4');
    await user.selectOptions(screen.getByLabelText('총 GPU 개수'), '1');
    expect(screen.getByRole('button', { name: '이 설정 사용하기' })).toBeDisabled();
    expect(screen.getByRole('alert')).toHaveTextContent('FSDP는 GPU 2개 이상');
    await user.selectOptions(screen.getByLabelText('총 GPU 개수'), '4');
    await user.click(screen.getByRole('button', { name: '이 설정 사용하기' }));
    await user.click(screen.getByRole('button', { name: '다음: 최종 확인' }));
    expect(screen.getAllByText('큰 모델을 여러 GPU에 나눠 담습니다.')).toHaveLength(2);
    await user.click(screen.getByRole('button', { name: '학습 시작' }));
    expect(screen.getByRole('heading', { name: 'my-fsdp-training' })).toBeInTheDocument();
    expect(screen.getByText('FSDP · GPU 4개')).toBeInTheDocument();
    expect(screen.getByText('내 모델 / custom-v99', { exact: true })).toBeInTheDocument();
    expect(screen.getByText('anything://내 데이터/mixed.bin', { exact: true })).toBeInTheDocument();
    expect(screen.getByText('train.py', { exact: true })).toBeInTheDocument();
  });
  it('accepts an arbitrary uploaded dataset without requiring a custom script', async () => {
    const user = userEvent.setup();
    render(<App />);
    await user.click(screen.getByRole('button', { name: '새 학습 만들기' }));
    await user.type(screen.getByLabelText('학습 이름'), 'uploaded-training');
    await user.type(screen.getByLabelText('학습 모델'), '/models/내 모델');
    await user.click(screen.getByRole('button', { name: '다음: 데이터 입력' }));
    await user.selectOptions(screen.getByLabelText('데이터 입력 방법'), 'upload');
    await user.upload(screen.getByLabelText('학습 데이터 파일'), new File(['opaque'], 'arbitrary.blob', { type: 'application/octet-stream' }));
    await user.click(screen.getByRole('button', { name: '다음: 학습 방식' }));
    await user.click(screen.getByRole('button', { name: '다음: 최종 확인' }));
    await user.click(screen.getByRole('button', { name: '학습 시작' }));
    expect(screen.getByText('arbitrary.blob', { exact: true })).toBeInTheDocument();
    expect(screen.getByText('/models/내 모델', { exact: true })).toBeInTheDocument();
    expect(screen.getByText(/준비된 train.py에 모델/)).toBeInTheDocument();
  });
});
